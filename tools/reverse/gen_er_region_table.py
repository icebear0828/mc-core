#!/usr/bin/env python3
"""Generate include/mc/er_region_table.hpp from Smithbox's Elden Ring map ID list.

Usage:
    python tools/reverse/gen_er_region_table.py path/to/map_ids.txt

The map ID list is Documentation/Game Information/ER/Map/Info - Map IDs.txt in
vawser/Smithbox. Each line is `m<area>_<gx>_<gz>_<lod> <place name>`, which is the
same encoding as the player's block id at PlayerIns+0x6D0:
    raw = area<<24 | gx<<16 | gz<<8 | lod

The zone mapping below is a keyword heuristic, not game data: it is the starting
point for the in-game ZONEPROBE run, not a verified region table.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "include" / "mc" / "er_region_table.hpp"

LINE = re.compile(r"^(m\d{2})_(\d{2})_(\d{2})_(\d{2})\s*(.*)$")


def zone_for(name: str) -> str:
    n = name.lower()
    # Underground / lava / crystal first: these names can also contain "cave".
    if "volcano" in n:
        return "Volcano"
    if "crystal" in n:
        return "CrystalCave"
    if "deeproot" in n or "eternal city" in n or "nokron" in n or "nokstella" in n:
        return "Deeproot"
    if "siofra" in n or "ainsel" in n or "mohgwyn" in n or "lake of rot" in n:
        return "Cave"
    if any(k in n for k in ("catacomb", "tunnel", "cave", "hero's grave", "tomb", "grotto", "shunning-ground")):
        return "Cave"
    if any(k in n for k in ("stormveil", "leyndell", "raya lucaria", "academy", "haligtree",
                            "farum azula", "divine tower", "roundtable", "chapel", "castle",
                            "manor", "shrine", "fort", "ruins")):
        return "StoneSurface"
    # Open-world surfaces: grass/dirt/snow; the ground material rule can still turn them to stone.
    if any(k in n for k in ("limgrave", "liurnia", "caelid", "altus", "mountaintop", "snowfield",
                            "weeping peninsula", "moonlight altar", "consecrated", "gravesite",
                            "scadu", "shadow keep", "belurat", "ensis", "cerulean", "rauh",
                            "jagged peak", "finger ruins", "abyssal", "charo")):
        return "Grassland"
    return "Grassland"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    entries: dict[int, tuple[str, str]] = {}
    for line in src.read_text(encoding="utf-8-sig").splitlines():
        m = LINE.match(line.strip())
        if not m:
            continue
        area = int(m.group(1)[1:])
        gx, gz, lod = (int(m.group(i)) for i in (2, 3, 4))
        name = m.group(5).strip()
        raw = (area << 24) | (gx << 16) | (gz << 8) | lod
        zone = zone_for(name)
        if raw in entries and entries[raw][1] != zone:
            print(f"warning: {raw:08X} maps to both {entries[raw][0]!r}/{entries[raw][1]} and {name!r}/{zone}; keeping the first")
            continue
        entries.setdefault(raw, (name, zone))

    order = ["Grassland", "StoneSurface", "Cave", "CrystalCave", "Volcano", "Deeproot"]
    counts = {z: 0 for z in order}
    for _, zone in entries.values():
        counts[zone] += 1

    lines = [
        "// Auto-generated by tools/reverse/gen_er_region_table.py - DO NOT EDIT.",
        "// Source: Smithbox Documentation/Game Information/ER/Map/Info - Map IDs.txt",
        "// (vawser/Smithbox). The block id is area<<24 | gx<<16 | gz<<8 | lod, the same encoding",
        "// as PlayerIns+0x6D0. The zone per row is a keyword heuristic, not verified game data:",
        "// it is the starting point for the in-game ZONEPROBE run.",
        "#pragma once",
        "",
        '#include "mc/zone_detector.hpp"',
        "",
        "namespace mc::er_region {",
        "",
        f"// {len(entries)} map blocks: " + ", ".join(f"{z} {counts[z]}" for z in order),
        "inline constexpr ZoneRule kEntries[] = {",
    ]
    for raw in sorted(entries):
        name, zone = entries[raw]
        safe = name.replace("*/", "* /")
        lines.append(f"    {{0x{raw:08X}u, LootZone::{zone}}}, // {safe}")
    lines += [
        "};",
        "",
        "inline constexpr std::span<const ZoneRule> kTable{kEntries};",
        "",
        "} // namespace mc::er_region",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} with {len(entries)} entries: " + ", ".join(f"{z}={counts[z]}" for z in order))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
